//! Regenerates the fixed-base comb tables used by `src/crypto/x25519.zig`.

const std = @import("std");

const Edwards25519 = std.crypto.ecc.Edwards25519;
const Fe = Edwards25519.Fe;
const comb_groups = 4;
const comb_width = 5;
const comb_entries = 1 << comb_width;
const comb_windows = 13;
const point_count = comb_groups * comb_entries;

const Tables = struct {
    cached: [comb_groups][3][5][comb_entries]u64,
    initial: [3][5][comb_entries]u64,
};

pub fn main(init: std.process.Init) !void {
    const tables = buildTables();
    const file = try std.Io.Dir.cwd().createFile(
        init.io,
        "src/crypto/x25519_tables.zig",
        .{},
    );
    defer file.close(init.io);

    var buffer: [16 * 1024]u8 = undefined;
    var file_writer = file.writer(init.io, &buffer);
    const writer = &file_writer.interface;
    try writer.writeAll(
        "//! Generated by `tools/generate_x25519_tables.zig`; do not edit.\n\n",
    );
    try writeCached(writer, tables.cached);
    try writer.writeByte('\n');
    try writeInitial(writer, tables.initial);
    try writer.flush();
}

fn writeCached(
    writer: *std.Io.Writer,
    values: [comb_groups][3][5][comb_entries]u64,
) !void {
    try writer.print(
        "pub const cached: [{d}][3][5][{d}]u64 = .{{\n",
        .{ comb_groups, comb_entries },
    );
    for (values) |group| {
        try writer.writeAll("    .{\n");
        for (group) |coordinate| {
            try writer.writeAll("        .{\n");
            for (coordinate) |limb| {
                try writer.writeAll("            .{");
                for (limb) |value| try writer.print(" {d},", .{value});
                try writer.writeAll(" },\n");
            }
            try writer.writeAll("        },\n");
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n");
}

fn writeInitial(
    writer: *std.Io.Writer,
    values: [3][5][comb_entries]u64,
) !void {
    try writer.print(
        "pub const initial: [3][5][{d}]u64 = .{{\n",
        .{comb_entries},
    );
    for (values) |coordinate| {
        try writer.writeAll("    .{\n");
        for (coordinate) |limb| {
            try writer.writeAll("        .{");
            for (limb) |value| try writer.print(" {d},", .{value});
            try writer.writeAll(" },\n");
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n");
}

fn buildTables() Tables {
    const column_count = comb_groups * comb_width;
    var columns: [column_count]Edwards25519 = undefined;
    columns[0] = Edwards25519.basePoint;
    for (1..column_count) |column| {
        var point = columns[column - 1];
        for (0..comb_windows) |_| point = point.dbl();
        columns[column] = point;
    }

    var points: [comb_groups][comb_entries]Edwards25519 = undefined;
    for (0..comb_groups) |group| {
        points[group][0] = Edwards25519.identityElement;
        points[group][1] = columns[group * comb_width];
        for (2..comb_entries) |index| {
            const column: std.math.Log2Int(usize) = @intCast(@ctz(index));
            points[group][index] = points[group][
                index ^
                    (@as(usize, 1) << column)
            ].add(
                columns[group * comb_width + column],
            );
        }
    }

    var prefixes: [point_count]Fe = undefined;
    var product = Fe.one;
    for (0..point_count) |flat_index| {
        prefixes[flat_index] = product;
        const group = flat_index / comb_entries;
        const index = flat_index % comb_entries;
        product = product.mul(points[group][index].z);
    }

    var tables: Tables = undefined;
    var inverse_product = product.invert();
    var flat_index: usize = point_count;
    while (flat_index != 0) {
        flat_index -= 1;
        const group = flat_index / comb_entries;
        const index = flat_index % comb_entries;
        const point = points[group][index];
        const inverse = inverse_product.mul(prefixes[flat_index]);
        inverse_product = inverse_product.mul(point.z);
        const x = point.x.mul(inverse);
        const y = point.y.mul(inverse);
        const t = point.t.mul(inverse);
        const cached = [3]Fe{
            y.add(x),
            y.sub(x),
            t.mul(Fe.edwards25519d2),
        };
        inline for (0..5) |limb| {
            inline for (0..3) |coordinate| {
                tables.cached[group][coordinate][limb][index] =
                    cached[coordinate].limbs[limb];
            }
            if (group == 0) {
                tables.initial[0][limb][index] = x.limbs[limb];
                tables.initial[1][limb][index] = y.limbs[limb];
                tables.initial[2][limb][index] = t.limbs[limb];
            }
        }
    }
    return tables;
}
