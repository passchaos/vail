//! Regenerates the signed fixed-base table used by
//! `src/crypto/ed25519_base_adx.zig`.

const std = @import("std");

const Curve = std.crypto.ecc.Edwards25519;
const Fe = Curve.Fe;
const scalar_bits = 251;
const window_bits = 5;
const windows = (scalar_bits + window_bits - 1) / window_bits;
const entries = 1 << (window_bits - 1);
const point_count = windows * entries;

pub fn main(init: std.process.Init) !void {
    const table = buildTable();
    const file = try std.Io.Dir.cwd().createFile(
        init.io,
        "src/crypto/ed25519_base_table.zig",
        .{},
    );
    defer file.close(init.io);

    var buffer: [16 * 1024]u8 = undefined;
    var file_writer = file.writer(init.io, &buffer);
    const writer = &file_writer.interface;
    try writer.writeAll(
        "//! Generated by `tools/generate_ed25519_base_table.zig`; " ++
            "do not edit.\n\n",
    );
    try writer.print(
        "pub const window_bits = {d};\n" ++
            "pub const table: [{d}][{d}][12]u64 align(64) = .{{\n",
        .{ window_bits, windows, entries },
    );
    for (table) |window| {
        try writer.writeAll("    .{\n");
        for (window) |entry| {
            try writer.writeAll("        .{");
            for (entry) |limb| try writer.print(" {d},", .{limb});
            try writer.writeAll(" },\n");
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n");
    try writer.flush();
}

fn buildTable() [windows][entries][12]u64 {
    var points: [windows][entries]Curve = undefined;
    var window_base = Curve.basePoint;
    for (0..windows) |window| {
        points[window][0] = window_base;
        for (1..entries) |index| {
            points[window][index] = points[window][index - 1].add(window_base);
        }
        inline for (0..window_bits) |_| window_base = window_base.dbl();
    }

    var prefixes: [point_count]Fe = undefined;
    var product = Fe.one;
    for (0..point_count) |flat_index| {
        prefixes[flat_index] = product;
        const window = flat_index / entries;
        const index = flat_index % entries;
        product = product.mul(points[window][index].z);
    }

    var table: [windows][entries][12]u64 = undefined;
    var inverse_product = product.invert();
    var flat_index: usize = point_count;
    while (flat_index != 0) {
        flat_index -= 1;
        const window = flat_index / entries;
        const index = flat_index % entries;
        const point = points[window][index];
        const inverse = inverse_product.mul(prefixes[flat_index]);
        inverse_product = inverse_product.mul(point.z);
        const x = point.x.mul(inverse);
        const y = point.y.mul(inverse);
        const cached = [3]Fe{
            y.sub(x),
            y.add(x),
            x.mul(y).mul(Fe.edwards25519d2),
        };
        inline for (0..cached.len) |coordinate| {
            const bytes = cached[coordinate].toBytes();
            inline for (0..4) |limb| {
                table[window][index][coordinate * 4 + limb] =
                    std.mem.readInt(
                        u64,
                        bytes[limb * 8 ..][0..8],
                        .little,
                    );
            }
        }
    }
    return table;
}
