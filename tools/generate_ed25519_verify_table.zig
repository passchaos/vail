//! Regenerates the fixed-generator table used by Ed25519 verification.

const std = @import("std");

const Curve = std.crypto.ecc.Edwards25519;
const Fe = Curve.Fe;
const entries = 1024;

pub fn main(init: std.process.Init) !void {
    var projective: [entries]Curve = undefined;
    projective[0] = Curve.basePoint;
    const twice = Curve.basePoint.dbl();
    for (1..entries) |index| {
        projective[index] = projective[index - 1].add(twice);
    }

    var prefixes: [entries]Fe = undefined;
    var product = Fe.one;
    for (projective, 0..) |point, index| {
        prefixes[index] = product;
        product = product.mul(point.z);
    }
    var inverse_product = product.invert();
    var table: [entries][12]u64 = undefined;
    var index: usize = entries;
    while (index != 0) {
        index -= 1;
        const inverse = inverse_product.mul(prefixes[index]);
        inverse_product = inverse_product.mul(projective[index].z);
        const x = projective[index].x.mul(inverse);
        const y = projective[index].y.mul(inverse);
        const cached = [3]Fe{
            y.sub(x),
            y.add(x),
            x.mul(y).mul(Fe.edwards25519d2),
        };
        inline for (0..cached.len) |coordinate| {
            const bytes = cached[coordinate].toBytes();
            inline for (0..4) |limb| {
                table[index][coordinate * 4 + limb] = std.mem.readInt(
                    u64,
                    bytes[limb * 8 ..][0..8],
                    .little,
                );
            }
        }
    }

    const file = try std.Io.Dir.cwd().createFile(
        init.io,
        "src/crypto/ed25519_verify_table.zig",
        .{},
    );
    defer file.close(init.io);
    var buffer: [16 * 1024]u8 = undefined;
    var file_writer = file.writer(init.io, &buffer);
    const writer = &file_writer.interface;
    try writer.writeAll(
        "//! Generated by `tools/generate_ed25519_verify_table.zig`; " ++
            "do not edit.\n\n" ++
            "pub const base_wnaf_12: [1024][12]u64 = .{\n",
    );
    for (table) |entry| {
        try writer.writeAll("    .{");
        for (entry) |limb| try writer.print(" {d},", .{limb});
        try writer.writeAll(" },\n");
    }
    try writer.writeAll("};\n");
    try writer.flush();
}
