//! Regenerate `src/x509/stringprep_data.zig` from `tools/stringprep_input.txt`.
//!
//! The input table was extracted from the checked-in data. Replacing it with
//! vendored Unicode 3.2 / RFC 3454 inputs is tracked in docs/third-party.md.

const std = @import("std");

const Section = enum {
    none,
    values,
    combining,
    mappings,
    prohibited,
};

pub fn main(init: std.process.Init) !void {
    const allocator = std.heap.page_allocator;
    const io = init.io;

    const input = try std.Io.Dir.cwd().readFileAlloc(
        io,
        "tools/stringprep_input.txt",
        allocator,
        std.Io.Limit.limited(16 << 20),
    );
    defer allocator.free(input);

    var values: std.ArrayList(u64) = .empty;
    var combining: std.ArrayList(u64) = .empty;
    var mappings: std.ArrayList(u64) = .empty;
    var prohibited: std.ArrayList(u64) = .empty;

    var section: Section = .none;
    var lines = std.mem.tokenizeScalar(u8, input, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (trimmed.len == 0 or trimmed[0] == '#') continue;
        if (std.mem.eql(u8, trimmed, "[values]")) {
            section = .values;
            continue;
        }
        if (std.mem.eql(u8, trimmed, "[combining]")) {
            section = .combining;
            continue;
        }
        if (std.mem.eql(u8, trimmed, "[mappings]")) {
            section = .mappings;
            continue;
        }
        if (std.mem.eql(u8, trimmed, "[prohibited]")) {
            section = .prohibited;
            continue;
        }
        if (section == .none) return error.InvalidInput;

        var tokens = std.mem.tokenizeAny(u8, trimmed, " \t;");
        while (tokens.next()) |token| {
            const value = try std.fmt.parseInt(u64, token, 16);
            switch (section) {
                .values => try values.append(allocator, value),
                .combining => try combining.append(allocator, value),
                .mappings => try mappings.append(allocator, value),
                .prohibited => try prohibited.append(allocator, value),
                .none => unreachable,
            }
        }
    }

    const file = try std.Io.Dir.cwd().createFile(
        io,
        "src/x509/stringprep_data.zig",
        .{},
    );
    defer file.close(io);

    var buffer: [16 * 1024]u8 = undefined;
    var file_writer = file.writer(io, &buffer);
    const writer = &file_writer.interface;

    try writer.writeAll(
        "//! Unicode 3.2 data used by the RFC 4518 caseIgnoreMatch implementation.\n" ++
            "//!\n" ++
            "//! Generated by `tools/generate_stringprep_data.zig` from\n" ++
            "//! `tools/stringprep_input.txt`; do not edit.\n" ++
            "//!\n" ++
            "//! Mapping entries pack `source << 24 | value_offset << 8 | value_len`.\n" ++
            "//!\n" ++
            "//! Unicode data is copyright Unicode, Inc. and distributed under the\n" ++
            "//! Unicode Data Files and Software License: https://www.unicode.org/license.txt\n\n",
    );

    try writeArray(u64, writer, "mappings", mappings.items, 6);
    try writeArray(u21, writer, "mapping_values", values.items, 12);
    try writeArray(u32, writer, "combining_classes", combining.items, 8);
    try writeArray(u64, writer, "prohibited_ranges", prohibited.items, 6);

    try writer.flush();
}

fn writeArray(
    comptime T: type,
    writer: *std.Io.Writer,
    name: []const u8,
    items: []const u64,
    per_line: usize,
) !void {
    try writer.print("pub const {s} = [_]{s}{{\n", .{ name, @typeName(T) });
    for (items, 0..) |value, index| {
        if (index % per_line == 0) try writer.writeAll("    ");
        try writer.print("0x{x},", .{value});
        if (index % per_line == per_line - 1 or index == items.len - 1) {
            try writer.writeByte('\n');
        } else {
            try writer.writeByte(' ');
        }
    }
    try writer.writeAll("};\n\n");
}
