//! Regenerates the fixed-generator tables used by `src/crypto/ec/p384.zig`.

const std = @import("std");

const P384 = std.crypto.ecc.P384;
const wnaf_entries = 256;
const comb_groups = 4;
const comb_width = 6;
const comb_entries = 1 << comb_width;
const comb_windows = 16;

pub fn main(init: std.process.Init) !void {
    var wnaf: [2][wnaf_entries][6]u64 = undefined;
    for (0..wnaf_entries) |index| {
        var scalar = [_]u8{0} ** 48;
        std.mem.writeInt(u16, scalar[0..2], @intCast(2 * index + 1), .little);
        const point = try P384.basePoint.mulPublic(scalar, .little);
        const affine = point.affineCoordinates();
        wnaf[0][index] = affine.x.limbs;
        wnaf[1][index] = affine.y.limbs;
    }

    var comb: [comb_groups][2][6][comb_entries]u64 = undefined;
    for (0..comb_groups) |group| {
        for (0..comb_entries) |index| {
            // Entry zero is the same harmless dummy as entry one. The secret
            // multiplier discards it with a conditional move.
            const effective_index = if (index == 0) 1 else index;
            var scalar = [_]u8{0} ** 48;
            for (0..comb_width) |column| {
                if ((effective_index &
                    (@as(usize, 1) << @as(u6, @intCast(column)))) == 0)
                {
                    continue;
                }
                const bit_index =
                    (group * comb_width + column) * comb_windows;
                scalar[bit_index / 8] |=
                    @as(u8, 1) << @intCast(bit_index % 8);
            }
            const point = try P384.basePoint.mulPublic(scalar, .little);
            const affine = point.affineCoordinates();
            inline for (0..6) |limb| {
                comb[group][0][limb][index] = affine.x.limbs[limb];
                comb[group][1][limb][index] = affine.y.limbs[limb];
            }
        }
    }

    const file = try std.Io.Dir.cwd().createFile(
        init.io,
        "src/crypto/ec/p384_tables.zig",
        .{},
    );
    defer file.close(init.io);
    var buffer: [16 * 1024]u8 = undefined;
    var file_writer = file.writer(init.io, &buffer);
    const writer = &file_writer.interface;
    try writer.writeAll(
        "//! Generated by `tools/generate_p384_tables.zig`; do not edit.\n\n" ++
            "pub const base_wnaf_10: [2][256][6]u64 = .{\n",
    );
    for (wnaf) |coordinate| {
        try writer.writeAll("    .{\n");
        for (coordinate) |limbs| {
            try writer.writeAll("        .{");
            for (limbs) |limb| try writer.print(" {d},", .{limb});
            try writer.writeAll(" },\n");
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n\n");
    try writer.writeAll(
        "pub const base_comb_4x6: [4][2][6][64]u64 = .{\n",
    );
    for (comb) |group| {
        try writer.writeAll("    .{\n");
        for (group) |coordinate| {
            try writer.writeAll("        .{\n");
            for (coordinate) |limb_values| {
                try writer.writeAll("            .{");
                for (limb_values) |limb| try writer.print(" {d},", .{limb});
                try writer.writeAll(" },\n");
            }
            try writer.writeAll("        },\n");
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n");
    try writer.flush();
}
